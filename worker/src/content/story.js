// Утилита: плоский порядок прохождения — пролог, затем сцены каждого акта по очереди.
export function flattenStory() {
  const flat = [];
  for (const s of STORY.prologue.scenes) {
    flat.push({ ...s, actId: 'prologue', actTitle: STORY.prologue.title });
  }
  for (const act of STORY.acts) {
    if (act.todo) {
      flat.push({
        id: `${act.id}_todo`,
        type: 'narrative',
        title: act.title,
        text: [
          `Скоро здесь будет сцена: ${act.title}.`,
          act.note || '',
          'Контент этого акта ещё не написан — отметьте для автора игры.',
        ],
        actId: act.id,
        actTitle: act.title,
      });
      continue;
    }
    for (const s of act.scenes) {
      flat.push({ ...s, actId: act.id, actTitle: act.title });
    }
  }
  return flat;
}
