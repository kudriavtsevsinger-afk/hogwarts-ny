const key = [
  ['Решительность', 'Любознательность', 'Хитрость', 'Доброта'],
  ['Смелость', 'Осторожность', 'Самостоятельность', 'Терпение'],
  ['Упорство', 'Мудрость', 'Амбициозность', 'Дисциплина'],
  ['Честность', 'Находчивость', 'Общительность', 'Преданность'],
  ['Находчивость', 'Сдержанность', 'Интуиция', 'Справедливость'],
  ['Смелость', 'Осторожность', 'Хитрость', 'Преданность'],
  ['Честность', 'Мудрость', 'Амбициозность', 'Доброта'],
  ['Упорство', 'Творчество', 'Самостоятельность', 'Дисциплина']
];
const roleByTrait = Object.fromEntries(Object.entries(roles).flatMap(
  ([role, traits]) => traits.map(trait => [trait, role])
));
function score(answers) {
  const traits = answers.map((choice, i) => key[i][choice]);
  const votes = traits.map(trait => roleByTrait[trait]);
  const totals = Object.fromEntries(Object.keys(roles).map(
    role => [role, votes.filter(vote => vote === role).length]
  ));
  const highest = Math.max(...Object.values(totals));
  const priority = [7, 0, 6, 5, 4, 3, 2, 1];
  const role = priority.map(i => votes[i]).find(vote => totals[vote] === highest);
  const counts = roles[role].map(trait => traits.filter(value => value === trait).length);
  const strongest = roles[role].filter((_, i) => counts[i] === Math.max(...counts));
  return { role, strongest };
}
